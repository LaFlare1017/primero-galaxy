import { readFile } from 'fs/promises';
import path from 'path';

export type FinbenchTrack = 'asc606' | 'govcon';

export interface FinbenchSummary {
  tasks: number;
  numeric_accuracy: number | null;
  groundedness: number;
  citation_validity: number;
  structure: number;
}

export interface FinbenchTaskPublic {
  id: string;
  category: string;
  difficulty: string;
  provenance: string;
  prompt: string;
  required_citations: string[];
}

export interface FinbenchRunPublic {
  id: string;
  task_id: string;
  model_provider: string;
  model_version: string;
  numeric_accuracy: boolean | null;
  groundedness_score: number;
  citation_validity: number;
  structure_score: number;
  latency_ms: number;
  judge_rationale: string;
  response: string;
  run_at: string;
}

export type FinbenchFindingKind =
  | 'citation_gap'
  | 'numeric_miss'
  | 'groundedness_gap'
  | 'latency_outlier';

export interface FinbenchFinding {
  kind: FinbenchFindingKind;
  statement: string;
  model_version: string;
  task_ids: string[];
  detail: Record<string, number>;
}

export interface FinbenchTrendModel {
  current: number;
  prior: number | null;
  change: number | null;
}

export interface FinbenchTrend {
  prior_month: string | null;
  models: Record<string, FinbenchTrendModel>;
}

export interface FinbenchSnapshot {
  track: FinbenchTrack;
  month: string;
  scorecard: {
    track: string;
    month: string;
    models: Record<string, FinbenchSummary>;
    categories: Record<string, FinbenchSummary>;
  };
  tasks: FinbenchTaskPublic[];
  runs: FinbenchRunPublic[];
  findings: FinbenchFinding[];
  trend: FinbenchTrend;
}


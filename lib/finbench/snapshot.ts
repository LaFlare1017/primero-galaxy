/**
 * Loads a published FinBench snapshot from public/finbench/. Snapshots are
 * generated by `finbench export-web` and contain no ground-truth answers.
 * Returns null when no snapshot has been published for the track.
 */
export async function loadSnapshot(
  track: FinbenchTrack,
): Promise<FinbenchSnapshot | null> {
  try {
    const file = path.join(process.cwd(), 'public', 'finbench', `${track}.json`);
    const raw = await readFile(file, 'utf8');
    return JSON.parse(raw) as FinbenchSnapshot;
  } catch {
    return null;
  }
}

export function modelLabel(provider: string, version: string): string {
  return `${provider} · ${version}`;
}

/** Numeric accuracy when the category has computed answers, else groundedness. */
export function cellMetric(
  runs: FinbenchRunPublic[],
): { value: number; kind: 'numeric' | 'groundedness' } {
  const numeric = runs.filter((r) => r.numeric_accuracy !== null);
  if (numeric.length > 0) {
    return {
      value: numeric.filter((r) => r.numeric_accuracy).length / numeric.length,
      kind: 'numeric',
    };
  }
  return {
    value: runs.reduce((sum, r) => sum + r.groundedness_score, 0) / runs.length,
    kind: 'groundedness',
  };
}
